def run_pipeline():
    # Phase 2: Generate data and run the implementation scripts.
    print("\n" + "#" * 72)
    print("PHASE 2: DATA GENERATION AND PIPELINE EXECUTION")
    print("#" * 72)

    for name, command in PIPELINE_STEPS:
        run_step(
            phase="Generation",
            name=name,
            command=command,
        )

def run_all_validations():
    # Validate existing generated outputs.
    print("\n" + "#" * 72)
    print("PHASE: VALIDATION")
    print("#" * 72)

    validation_steps = [
        (
            "validations/part_a_validations.py",
            False,
        ),
        (
            "validations/part_b_validations.py",
            False,
        ),
        (
            "validations/part_c_validations.py",
            True,
        ),
        (
            "validations/part_d_validations.py",
            False,
        ),
    ]

    for script, part_c_exception in validation_steps:
        run_validation_step(
            script,
            part_c_exception=part_c_exception,
        )

def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Run the Delhivery Last-Mile Delay Intelligence pipeline "
            "with optional validation."
        )
    )

    parser.add_argument(
        "--mode",
        choices=["full", "pipeline-only", "validate-only"],
        default="full",
        help=(
            "full: regenerate artifacts and run validations; "
            "pipeline-only: regenerate artifacts without validations; "
            "validate-only: validate existing artifacts without "
            "regenerating them."
        ),
    )

    return parser.parse_args()

# ============================================================
# MAIN
# ============================================================
def main():
    args = parse_args()

    print("=" * 72)
    print("DELHIVERY LAST-MILE DELAY INTELLIGENCE")
    print(f"Execution mode: {args.mode}")
    print("=" * 72)

    try:
        # Check prerequisites before deleting generated artifacts.
        preflight_checks()

        if args.mode == "validate-only":
            # Validate existing artifacts.
            # Do not clean or regenerate anything.
            run_all_validations()

        else:
            # Clean previously generated artifacts.
            clean_generated_artifacts()

            # Generate data and execute the pipeline.
            run_pipeline()

            if args.mode == "pipeline-only":
                print()
                print("=" * 72)
                print("PIPELINE COMPLETED — VALIDATIONS SKIPPED")
                print("Generated artifacts have NOT been validated.")
                print("Run with --mode validate-only to validate them.")
                print("=" * 72)
                return 0

            # Full mode: run all validations.
            run_all_validations()

        print()
        print("=" * 72)
        print("CLEAN RUN COMPLETED SUCCESSFULLY")
        print("=" * 72)

        return 0

    except Exception as exc:
        print()
        print("!" * 72)
        print("CLEAN RUN FAILED")
        print(f"Error: {exc}")
        print("Execution stopped. Investigate the failure before continuing.")
        print("!" * 72)

        return 1

if __name__ == "__main__":
    raise SystemExit(main())