def run_step(phase, name, command):
    """Execute a script and stop if it returns a nonzero exit code."""

    full_command = [PYTHON, *command]

    print("\n" + "-" * 72)
    print(f"START: {name}")
    print(f"PHASE: {phase}")
    print(f"COMMAND: {' '.join(full_command)}")
    print("-" * 72, flush=True)

    result = subprocess.run(
        full_command,
        cwd=ROOT,
        check=False,
    )

    if result.returncode != 0:
        raise RuntimeError(
            f"{name} failed with exit code {result.returncode}."
        )

    print(f"PASS: {name}", flush=True)

def validate_approved_part_c_exception(report_path):
    """
    Accept only the previously agreed Part C validation mismatch.

    The validation report itself is not modified:
    the approved metric remains MISMATCH.

    Returns True only when:
    - The report exists and has the expected schema.
    - Exactly one MISMATCH exists.
    - The mismatch is default_rf_validation_f1.
    - Its reference, observed value, and tolerance match the
      previously agreed values.
    - Its observed F1 satisfies the business criterion (> 0.65).
    - Every other metric is PASS.
    - No metric has ERROR status.
    """

    report_path = ROOT / report_path

    if not report_path.is_file():
        print(
            "ERROR: Part C validation report not found: "
            f"{report_path}"
        )
        return False

    required_columns = {
        "source_file",
        "metric_name",
        "reference_value",
        "code_value",
        "tolerance",
        "status",
        "comment",
    }

    try:
        with report_path.open(
            mode="r",
            newline="",
            encoding="utf-8-sig",
        ) as file:
            reader = csv.DictReader(file)

            if not reader.fieldnames:
                print("ERROR: Part C validation report is empty.")
                return False

            missing_columns = required_columns - set(reader.fieldnames)

            if missing_columns:
                print(
                    "ERROR: Part C validation report is missing "
                    f"columns: {sorted(missing_columns)}"
                )
                return False

            rows = list(reader)

    except (OSError, csv.Error) as exc:
        print(f"ERROR: Could not read Part C validation report: {exc}")
        return False

    if not rows:
        print("ERROR: Part C validation report contains no metrics.")
        return False

    # Reject missing or unexpected validation statuses.
    allowed_statuses = {"PASS", "MISMATCH", "ERROR"}

    for row in rows:
        status = row["status"].strip().upper()

        if status not in allowed_statuses:
            print(
                "ERROR: Unexpected or missing status in Part C report "
                f"for metric {row['metric_name']!r}: {status!r}"
            )
            return False

    errors = [
        row for row in rows
        if row["status"].strip().upper() == "ERROR"
    ]

    if errors:
        print(
            f"ERROR: Part C report contains {len(errors)} ERROR metric(s)."
        )
        return False

    mismatches = [
        row for row in rows
        if row["status"].strip().upper() == "MISMATCH"
    ]

    # The approved exception is the ONLY mismatch we permit.
    if len(mismatches) != 1:
        print(
            "ERROR: Expected exactly one acknowledged Part C mismatch; "
            f"found {len(mismatches)}."
        )
        return False

    row = mismatches[0]

    if row["metric_name"].strip() != "default_rf_validation_f1":
        print(
            "ERROR: Part C mismatch is not the approved exception. "
            f"Found metric: {row['metric_name']!r}"
        )
        return False

    try:
        reference_value = float(row["reference_value"])
        code_value = float(row["code_value"])
        tolerance = float(row["tolerance"])
    except (TypeError, ValueError):
        print(
            "ERROR: Approved Part C exception has a missing or "
            "non-numeric reference value, code value, or tolerance."
        )
        return False

    if not all(
        math.isfinite(value)
        for value in (reference_value, code_value, tolerance)
    ):
        print("ERROR: Approved Part C exception contains a non-finite value.")
        return False

    # Verify the original, agreed benchmark.
    if not math.isclose(
        reference_value,
        0.8000,
        rel_tol=0.0,
        abs_tol=1e-9,
    ):
        print(
            "ERROR: Approved exception reference changed. "
            f"Expected 0.8000; found {reference_value}."
        )
        return False

    if not math.isclose(
        tolerance,
        0.001,
        rel_tol=0.0,
        abs_tol=1e-9,
    ):
        print(
            "ERROR: Approved exception tolerance changed. "
            f"Expected 0.001; found {tolerance}."
        )
        return False

    # Verify the previously reviewed observed value.
    if not math.isclose(
        code_value,
        0.7848,
        rel_tol=0.0,
        abs_tol=1e-4,
    ):
        print(
            "ERROR: The observed Part C value differs from the "
            "previously reviewed exception. "
            f"Expected approximately 0.7848; found {code_value}."
        )
        return False

    if code_value <= 0.65:
        print(
            "ERROR: Part C default RF validation F1 does not satisfy "
            f"the agreed business criterion (> 0.65). Found {code_value}."
        )
        return False

    # All other metrics must pass.
    other_non_pass = [
        metric for metric in rows
        if metric is not row
        and metric["status"].strip().upper() != "PASS"
    ]

    if other_non_pass:
        print(
            "ERROR: Part C contains additional non-PASS metrics."
        )
        for metric in other_non_pass:
            print(
                f"  {metric['metric_name']}: "
                f"{metric['status']}"
            )
        return False

    print()
    print("ACKNOWLEDGED EXCEPTION: Part C validation")
    print("  Metric: default_rf_validation_f1")
    print(f"  Reference: {reference_value:.4f}")
    print(f"  Observed:  {code_value:.4f}")
    print(f"  Tolerance: {tolerance:.4f}")
    print("  Business criterion: F1 > 0.65 — SATISFIED")
    print("  Validation report status: MISMATCH — PRESERVED")
    print("  Decision: Continue with Part D validation.")
    print()

    return True

def run_validation_step(script, part_c_exception=False):
    """
    Run a validation script.

    Nonzero exit codes normally stop the clean run.
    Part C may continue only when its report contains the
    specifically approved mismatch and nothing else fails.
    """

    script_path = ROOT / script

    if not script_path.is_file():
        raise FileNotFoundError(
            f"Validation script not found: {script_path}"
        )

    print()
    print("=" * 72)
    print(f"RUNNING VALIDATION: {script}")
    print("=" * 72)

    result = subprocess.run(
        [PYTHON, str(script_path)],
        cwd=ROOT,
        check=False,
    )

    if result.returncode == 0:
        print(f"PASS: {script}")
        return

    if part_c_exception:
        report_path = Path(
            "validations/reports/part_c_validation_report.csv"
        )

        if validate_approved_part_c_exception(report_path):
            print(
                "CONTINUING: Part C has only the previously "
                "approved mismatch."
            )
            return

    raise RuntimeError(
        f"Validation failed: {script} "
        f"(exit code {result.returncode})."
    )

