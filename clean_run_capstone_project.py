def remove_generated_file(directory, filename):
    """Remove one explicitly identified generated file."""

    path = ROOT / directory / filename

    if path.is_file():
        path.unlink()
        print(f"  Deleted: {path.relative_to(ROOT)}")

def clean_generated_artifacts():
    """
    Delete generated artifacts only.

    Preserve:
    - Source code
    - Reference CSVs
    - Requirements and README
    - .gitkeep files
    - Python environment
    """

    print("\n" + "=" * 72)
    print("PHASE 1: CLEANING GENERATED ARTIFACTS")
    print("=" * 72)

    for filename in GENERATED_DATA_FILES:
        remove_generated_file("data", filename)

    for filename in GENERATED_MODEL_FILES:
        remove_generated_file("models", filename)

    for filename in GENERATED_OUTPUT_FILES:
        remove_generated_file("outputs", filename)

    for filename in GENERATED_VALIDATION_REPORTS:
        remove_generated_file("validations/reports", filename)

    print("\nPASS: generated artifact cleanup completed.")

